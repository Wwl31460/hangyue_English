def merge(affixes):
    """把补充表合并进 AFFIXES（重复成员自动跳过）。"""
    for key, words in EXTRA_AFFIXES.items():
        if key not in affixes:
            continue
        gloss, old = affixes[key]
        have = {w.lower() for w, _, _ in old}
        affixes[key] = (gloss, old + [t for t in words if t[0].lower() not in have])
    for key, (gloss, words) in NEW_FAMILIES.items():
        old = affixes.get(key, (gloss, []))[1]
        have = {w.lower() for w, _, _ in old}
        affixes[key] = (gloss, old + [t for t in words if t[0].lower() not in have])
    return affixes
